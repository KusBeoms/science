/**
 * 도감 조건은 앞 구역 풀에서 실제로 모을 수 있는 서로 다른 행성 수의 3/4 를 넘지 않게 낮춘다.
 * 행성이 약 80종으로 늘기 전(지금 25종)에는 표의 20·35·60종이 도달 불가라서 생기는 임시 보정이다.
 */
const dexReach = (i: number) => new Set(ROWS.slice(0, i).flatMap(r => r.pool)).size;
const capDex = (n: number, i: number) => Math.min(n, Math.max(1, Math.floor(dexReach(i) * 0.75)));

/** 기본값 채우기: 환경 배율 1, 해금 = 이전 섹터 통과 + 조건표(need), 혼자 도는 행성 수(solo)는 구역별 명시 */
export const SECTORS: Sector[] = ROWS.map(({need = {}, ...r}, i) => ({
  gravityMul: 1,
  timeMul: 1,
  units: [],
  solo: 10,
  ...r,
  requires: {...(i ? {prev: ROWS[i - 1].id} : {}), ...need, ...(need.dex ? {dex: capDex(need.dex, i)} : {})},
}));
export const sectorIndex = (id: string) => SECTORS.findIndex(s => s.id === id);
