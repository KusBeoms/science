/** 등급 가중치로 풀에서 하나 고른다. 풀은 비어 있으면 안 된다 (core/layout.ts 의 poolOf 가 대체 풀을 준다) */
export function pickFrom(pool: number[]): number {
  const w = pool.map(i => RW[P[i].t]),
    s = w.reduce((a, b) => a + b);
  let r = Math.random() * s;
  for (let k = 0; k < pool.length; k++) {
    r -= w[k];
    if (r <= 0) return pool[k];
  }
  return pool[0];
}
