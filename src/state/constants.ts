/* 전역 상수 + 시작 프리셋 테이블 */
(function () {
  "use strict";
  const G = (window.Game = window.Game || ({} as GameNamespace));

  G.SPEED = 0.1; // ly / sec
  G.FUEL_MAX = 750;
  G.BASE_BURN = 6;
  // 태양 질량(1 M☉)을 기준으로 삼는다 — mass 값은 그대로 "태양 질량 단위"로 취급된다.
  G.MASS_REF = 1;

  // 지구 질량(M⊕) — 태양질량/지구질량 비율 ≈ 332,946.
  G.EARTH_MASS = 1 / 332946;

  // 암석형(지구형) 행성과 가스형(목성형) 행성을 가르는 경계. 외계행성 관측에서
  // "반지름 계곡(radius valley)"이 약 1.7~2.0 지구반지름, 그 핵질량 함수가
  // 대략 4~8 M⊕ 부근에서 정점을 이룬다는 결과를 근거로 6 M⊕를 경계로 쓴다.
  G.GAS_GIANT_MIN_MASS = 6 * G.EARTH_MASS;

  // 수소 핵융합 최소질량(Hydrogen-Burning Minimum Mass). 이보다 가벼우면
  // 중심 압력·온도가 부족해 수소 핵융합이 점화되지 않는 갈색왜성/원시체로
  // 남는다 — 문헌상 0.075~0.08 M☉로 알려져 있어(예: A&A 2023 재산정),
  // 여기서는 0.08을 점화 임계값으로 쓴다.
  G.IGNITION_MASS = 0.08;

  // 실제 항성 진화의 초기(주계열 진입 시) 질량 경계값.
  //   < 8 M☉  → 백색왜성으로 생을 마감 (찬드라세카르 한계 1.4 M☉는 "핵"의 잔여
  //             질량 기준이라 게임의 "전체 질량" 임계값으로는 초기질량 경계인
  //             8 M☉를 쓴다 — 단일 항성 진화 이론에서 약 8 M☉ 이상이 최종적으로
  //             핵붕괴에 이른다는 것이 정설)
  //   8–20 M☉ → 초신성 후 중성자별
  //   > 20 M☉ → 블랙홀 (전형적으로 20 M☉ 안팎부터 초신성 폭발 에너지가
  //             외피를 뚫고 나오기 어려워져 "실패한 초신성"으로 곧장 블랙홀이 됨)
  G.WHITE_DWARF_MAX = 8;
  G.BLACK_HOLE_MIN = 20;

  // 어디까지 태울 수 있느냐는 중심 온도가 결정하고, 중심 온도는 질량이 정한다.
  //   < 0.5 M☉  : 완전대류 적색왜성. 축퇴된 중심핵이 헬륨 점화 온도(~1억 K)에
  //               끝내 도달하지 못해 수소만 태우고 끝난다 → 헬륨 백색왜성.
  //   0.5~8 M☉  : 헬륨까지 태우고 탄소-산소 핵을 남긴 채 멈춘다 → CO 백색왜성.
  //   8~11 M☉   : 탄소·네온까지 진행해 O-Ne-Mg 핵을 만든다 → 전자포획 초신성.
  //   ≥ 11 M☉   : 규소 연소까지 밀고 나가 철핵을 쌓는다 → 철핵 붕괴.
  G.HELIUM_IGNITION_MIN = 0.5;
  G.CARBON_IGNITION_MIN = 8;
  G.IRON_CORE_MIN = 11;

  // 형성기(점화 전)에 시간이 흐르는 속도(년/초). 원시행성계원반의 수명은
  // 관측상 대략 100만~1000만 년이고(적외선 초과 관측으로 젠 원반 비율이
  // 이 시간 규모에서 사라진다), 지구형 행성의 강착도 같은 시간대에 끝난다.
  // 형성기가 대략 40~90초 걸리므로 15만 년/초면 총 600만~1350만 년 —
  // 실제 원반 수명 범위 안에 들어온다.
  //
  // 이 값이 0이면(예전 구현) 형성기 내내 나이가 0년으로 멈춘 채 거리만
  // 쌓여서, 몇 광년을 "0년 만에" 이동하는 초광속이 돼버린다.
  G.FORMATION_YEARS_PER_SEC = 150000;

  // 플레이어 별이 평상시 머무는 화면 가로 위치(화면 폭 비율). 오른쪽에 도킹되는
  // 이벤트 팝업(css/style.css의 `#eventPopup { right:4vw; width:min(24rem,38vw) }`)과
  // 절대 겹치지 않도록 잡은 값이라, 팝업 폭/위치를 바꾸면 이 값도 함께 검토해야 한다.
  G.STAR_REST_X_FRACTION = 0.28;

  // 강착 억제 기준 질량. 별이 무거워질수록 복사압이 강해져 떨어져 들어오려는
  // 물질을 도로 밀어내고, 실제 대질량 별의 강착은 이 때문에 스스로 멎는다
  // (에딩턴 한계 근처에서 복사압이 중력을 상쇄 — 대질량 별 형성의 고전적 난제).
  // 그래서 같은 "질량 3배" 선택이라도 실제로 붙는 양은 무거울수록 줄어든다:
  // 억제율 = 1 / (1 + 현재질량 / 이 값). 8 M☉에서 절반, 20 M☉에서 약 29%.
  //
  // 게임 쪽 이유도 같다 — 배율이 복리로 누적되면 이벤트가 많은 판에서 질량이
  // 상한(200)까지 튀어 거의 모든 판이 블랙홀로 끝나버린다.
  G.ACCRETION_DAMP_MASS = 8;

  // 한 판에서 동반성을 만날 확률. 이벤트 뽑기 1회당이 아니라 "이번 판에
  // 동반성 서사가 등장하는가"를 판 시작 때 한 번만 굴린다 — 뽑기당 확률로
  // 두면 한 판에 20번 넘게 굴려져 실제 등장률이 70%를 넘어버린다.
  G.COMPANION_ENCOUNTER_CHANCE = 0.05;

  // 목성 질량(M_Jup) — 태양질량/목성질량 비율 ≈ 1047.35.
  G.JUPITER_MASS = 1 / 1047.35;

  // 세 프리셋은 "얼마나 빨리 자라느냐"가 아니라 "어디서부터 시작하느냐"로
  // 갈린다. 성운이 짙을수록 더 무거운 천체로 뭉쳐 태어나고, 그만큼 남은
  // 여정(형성기)이 짧아진다.
  //   고밀도 → 태양질량 항성. 이미 핵융합 중이라 형성기를 건너뛴다.
  //   표준   → 목성형 행성. 점화까지 몇 단계만 남았다.
  //   희박   → 지구형 행성. 처음부터 끝까지 전 과정을 겪는다.
  // volume은 실제 반지름이 아니라 순수 시각적 크기 스탯이라 질량 단위와 무관하게
  // 기존 스케일(6~160)을 유지한다. accretionBoost는 성운 밀도가 높을수록 원반
  // 물질을 더 빨리 끌어모은다는 뜻으로, 점화 전 이벤트 간격에 곱해진다.
  G.NEBULA_PRESETS = [
    { id: 'dense', name: '고밀도 성운', desc: '태양과 같은 항성으로 태어난다', mass: 1, volume: 46, accretionBoost: 1.6 },
    { id: 'standard', name: '표준 성운', desc: '목성형 행성에서 시작한다', mass: 1 * G.JUPITER_MASS, volume: 30, accretionBoost: 1.0 },
    { id: 'diffuse', name: '희박한 성운', desc: '지구형 행성에서 시작한다', mass: 1 * G.EARTH_MASS, volume: 20, accretionBoost: 0.65 },
  ];
})();
